#!/usr/bin/env python3
# Regenerate drivers/fb/font.c: rasterizes DejaVu Sans Mono into 8x16 cells
# with ffmpeg's drawtext (FreeType). Usage: tools/mkfont.py [font.ttf] > drivers/fb/font.c
import os, subprocess, sys, tempfile

ttf = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/TTF/DejaVuSansMono.ttf"
FIRST, LAST, W, H = 32, 126, 8, 16
n = LAST - FIRST + 1
with tempfile.TemporaryDirectory() as tmp:
    filters = []
    for c in range(FIRST, LAST + 1):
        path = os.path.join(tmp, "c%d.txt" % c)
        with open(path, "w") as f:
            f.write(chr(c))
        filters.append("drawtext=fontfile=%s:textfile=%s:expansion=none:y_align=font:"
                       "fontsize=13:fontcolor=white:x=%d:y=-1" % (ttf, path, (c - FIRST) * W))
    raw = os.path.join(tmp, "out.raw")
    subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi",
                    "-i", "color=black:s=%dx%d" % (n * W, H), "-vf", ",".join(filters),
                    "-frames:v", "1", "-f", "rawvideo", "-pix_fmt", "gray", raw], check=True)
    data = open(raw, "rb").read()

print("// 8x16 console font, ASCII 32-126. Generated by tools/mkfont.py from DejaVu")
print("// Sans Mono: Bitstream Vera Fonts Copyright (c) 2003 by Bitstream, Inc. All")
print("// Rights Reserved; DejaVu changes are in the public domain. Bitstream Vera is a")
print("// trademark of Bitstream, Inc. Redistributed under the Bitstream Vera license.")
print("#include <stdint.h>\n")
print("const uint8_t font8x16[%d][16] = {" % n)
for i in range(n):
    rows = []
    for y in range(H):
        b = 0
        for x in range(W):
            if data[y * n * W + i * W + x] > 90:
                b |= 0x80 >> x
        rows.append("0x%02x" % b)
    print("    { %s },  // %r" % (", ".join(rows), chr(FIRST + i)))
print("};")
